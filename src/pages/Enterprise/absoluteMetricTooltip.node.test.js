const assert = require('assert');
const fs = require('fs');
const path = require('path');
const data = require('./overviewData');
const samples = [{ timestamp: 1, used: 1.6, capacity: 8 }, { timestamp: 2, used: 4, capacity: 16 }];
const metrics = (absolute = { unit: 'cores', samples }) => ({ series: [{ values: [[1, 20], [2, 25]] }], absolute });
const lookup = data.absoluteMetricLookup(metrics(), 'cpu');
assert.deepStrictEqual(lookup.get(1000), { used: 1.6, capacity: 8, unit: 'cores' });
assert.deepStrictEqual(lookup.get(2000), { used: 4, capacity: 16, unit: 'cores' });
assert.strictEqual(lookup.get(1001), undefined, 'nearby timestamps must not be joined');
assert.strictEqual(data.absoluteMetricLookup(metrics(undefined), 'network').size, 0);
[null, {}, { unit: 'unknown', samples }, { unit: 'bytes', samples }, { unit: 'cores', samples: {} }].forEach(absolute => {
  assert.strictEqual(data.absoluteMetricLookup(metrics(absolute), 'cpu').size, 0);
});
const legacy = { series: metrics().series };
assert.strictEqual(data.absoluteMetricLookup(legacy, 'cpu').size, 0);
const invalid = [true, false, NaN, Infinity, -1, '1.6', null];
invalid.forEach(used => assert.strictEqual(data.absoluteMetricLookup(metrics({ unit: 'cores', samples: [{ timestamp: 1, used, capacity: 8 }] }), 'cpu').size, 0));
[0, -1, true, NaN, Infinity, '8', null].forEach(capacity => assert.strictEqual(data.absoluteMetricLookup(metrics({ unit: 'cores', samples: [{ timestamp: 1, used: 1.6, capacity }] }), 'cpu').size, 0));
[true, NaN, Infinity, -1, '1', null].forEach(timestamp => assert.strictEqual(data.absoluteMetricLookup(metrics({ unit: 'cores', samples: [{ timestamp, used: 1.6, capacity: 8 }] }), 'cpu').size, 0));
assert.strictEqual(data.absoluteMetricLookup(metrics({ unit: 'cores', samples: [{ timestamp: 1.001, used: 1.6, capacity: 8 }] }), 'cpu').size, 0);
assert.strictEqual(data.absoluteMetricLookup(metrics({ unit: 'cores', samples: [samples[0], { timestamp: 1, used: 2, capacity: 8 }] }), 'cpu').size, 0, 'conflicting duplicates cannot leak the first valid sample');
assert.strictEqual(data.absoluteMetricLookup(metrics({ unit: 'cores', samples: [samples[0], samples[0]] }), 'cpu').size, 1);
assert.strictEqual(data.absoluteMetricLookup({ ...metrics(), series: [{ values: [[1, 20], [1, 21]] }] }, 'cpu').size, 0);
const zero = { series: [{ values: [[1, 0]] }], absolute: { unit: 'cores', samples: [{ timestamp: 1, used: 0, capacity: 8 }] } };
assert.strictEqual(data.absoluteMetricLookup(zero, 'cpu').get(1000).used, 0);
const memory = { semantics: 'host_memory_working_set', series: [{ values: [[1, 25]] }], absolute: { unit: 'bytes', samples: [{ timestamp: 1, used: 2 ** 30, capacity: 4 * 2 ** 30 }] } };
assert.deepStrictEqual(data.formatMetricAmount(2 ** 30, 'bytes'), { value: 1, unit: 'GiB' });
assert.deepStrictEqual(data.formatMetricAmount(0.005, 'cores'), { value: 5, unit: 'mCore' });
assert.deepStrictEqual(data.formatMetricAmount(0, 'cores'), { value: 0, unit: 'Core' });
assert.strictEqual(data.formatMetricAmount(true, 'cores'), null);
assert.strictEqual(data.formatMetricAmount(1, '<script>'), null);
const options = { metric: 'cpu', lookup, timeLabel: '2026-10-20 12:30', seriesLabel: 'CPU utilization', unitLabel: '%', usageLabel: 'Usage / capacity', unavailableLabel: 'Actual usage temporarily unavailable' };
const first = data.metricTooltipHtml({ value: [1000, 20] }, options);
const second = data.metricTooltipHtml({ value: [2000, 25] }, options);
assert.ok(first.indexOf('1.6 Core / 8 Core') < first.indexOf('20.00 %'));
assert.ok(second.includes('4 Core / 16 Core') && second.includes('25.00 %'));
assert.ok(first.startsWith('2026-10-20 12:30'));
assert.ok(data.metricTooltipHtml({ value: [1000, 20] }, { ...options, lookup: new Map() }).includes(options.unavailableLabel));
const memoryHtml = data.metricTooltipHtml({ value: [1000, 25] }, { ...options, metric: 'memory', lookup: data.absoluteMetricLookup(memory, 'memory'), usageLabel: 'Working-set usage / capacity' });
assert.ok(memoryHtml.includes('Working-set usage / capacity: 1 GiB / 4 GiB'));
const networkHtml = data.metricTooltipHtml({ value: [1000, 1536] }, { ...options, metric: 'network', seriesLabel: 'RX + TX' });
assert.strictEqual(networkHtml, '2026-10-20 12:30<br/>RX + TX 1.5 KiB/s');
assert.ok(!data.metricTooltipHtml({ value: [1000, 20] }, { ...options, usageLabel: '<img onerror="x">' }).includes('<img'));
assert.strictEqual(data.metricTooltipHtml({ value: [1000, null] }, options), '');
for (let i = 0; i < 1000; i += 1) assert.strictEqual(data.metricTooltipHtml({ value: [1000, 20] }, options), first);
assert.strictEqual(lookup.size, 2, 'formatter must not mutate or rebuild measurements');
const component = fs.readFileSync(path.join(__dirname, 'components/ResourceTrend.js'), 'utf8');
assert.ok(component.indexOf('const lookup = overviewData.absoluteMetricLookup') < component.indexOf('formatter: params'));
assert.ok(!/fetch\(|dispatch\(|cluster.*capacity/.test(component), 'hover remains local; no network or current-capacity fallback');
console.log('absolute historical metric tooltip checks passed');
